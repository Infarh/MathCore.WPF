   Коллекция корректно обрабатывает все типы изменений:
   Add, Remove, Replace, Reset, Move

3. БЕЗОПАСНОЕ УПРАВЛЕНИЕ РЕСУРСАМИ
   IDisposable гарантирует полное освобождение подписок и ресурсов
   Безопасно вызывать Dispose() несколько раз

4. АСИНХРОННОСТЬ БЕЗ БЛОКИРОВОК
   ConfigureAwait(false) обеспечивает работу на не UI-потоке
   Команда AddCommand асинхронно создаёт элементы

5. РАСШИРЯЕМОСТЬ ЧЕРЕЗ СОБЫТИЯ
   События ItemAdded, ItemRemoved, ItemCreationFailed позволяют
   реагировать на операции в коллекции без изменения класса

